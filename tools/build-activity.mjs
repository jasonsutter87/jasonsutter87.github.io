// Reads commit history for every project in data/projects.js and writes data/activity.js.
// Run from the repo root: node tools/build-activity.mjs [path to Companies folder]
// Folders without git history fall back to their newest file's modified date.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execFileSync } from 'node:child_process';

const ROOT = process.argv[2] || path.join(os.homedir(), 'Documents/Companies');
const SKIP = /node_modules|\/target\/|\/\.git\/|\/dist\/|\/build\/|\.venv|__pycache__/;
const WEEKS = 53;

const window = {};
new Function('window', fs.readFileSync('data/projects.js', 'utf8'))(window);

const day = d => d.toISOString().slice(0, 10);
const today = new Date();
// The graph starts on the Sunday WEEKS weeks back, like GitHub's.
const start = new Date(today);
start.setUTCDate(start.getUTCDate() - start.getUTCDay() - (WEEKS - 1) * 7);
const dayIndex = iso => Math.floor((Date.parse(iso) - Date.parse(day(start))) / 864e5);

const gitDates = dir => {
  try {
    return execFileSync('git', ['-C', dir, 'log', '--all', '--format=%as'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] })
      .split('\n').filter(Boolean);
  } catch { return null; }
};

const newestFile = dir => {
  let newest = 0;
  const walk = d => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (SKIP.test(p + '/') || e.name.startsWith('.')) continue;
      if (e.isDirectory()) walk(p);
      else newest = Math.max(newest, fs.statSync(p).mtimeMs);
    }
  };
  walk(dir);
  return newest ? day(new Date(newest)) : null;
};

const projects = {};

for (const p of window.PROJECTS) {
  const dates = [];
  let fallback = null;
  for (const rel of p.git || []) {
    const dir = path.join(ROOT, rel);
    if (!fs.existsSync(dir)) { console.warn(`missing: ${rel}`); continue; }
    const g = fs.existsSync(path.join(dir, '.git')) ? gitDates(dir) : null;
    if (g && g.length) dates.push(...g);
    else fallback = [fallback, newestFile(dir)].filter(Boolean).sort().pop() || null;
  }
  dates.sort();
  // Sparse map of day index (0 = graph start) to commit count.
  const days = {};
  for (const d of dates) {
    const i = dayIndex(d);
    if (i >= 0 && i < WEEKS * 7) days[i] = (days[i] || 0) + 1;
  }
  projects[p.id] = {
    commits: dates.length,
    first: dates[0] || fallback,
    last: dates[dates.length - 1] || fallback,
    days,
  };
}

const out = { generated: day(today), start: day(start), weeks: WEEKS, projects };
fs.writeFileSync('data/activity.js', `// Generated by tools/build-activity.mjs on ${out.generated}. Do not edit.\nwindow.ACTIVITY = ${JSON.stringify(out)};\n`);
const total = Object.values(projects).reduce((n, p) => n + p.commits, 0);
const recent = Object.values(projects).reduce((n, p) => n + Object.values(p.days).reduce((a, b) => a + b, 0), 0);
console.log(`${window.PROJECTS.length} projects, ${total} commits, ${recent} in the last ${WEEKS} weeks`);
